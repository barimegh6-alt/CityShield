"""Generates backend/src/main/resources/db/schema.sql, JPA entities and Spring Data repositories from spec.py."""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from spec import TABLES

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
B = os.path.join(ROOT, "backend", "src", "main")
SQL = {"L": "BIGINT", "I": "INT", "D": "DOUBLE", "T": "DATETIME"}
JAVA = {"L": "Long", "I": "Integer", "D": "Double", "T": "LocalDateTime"}

def sqltype(t): return f"VARCHAR({t[1:]})" if t.startswith("S") else SQL[t]
def javatype(t): return "String" if t.startswith("S") else JAVA[t]
def camel(s):
    p = s.split("_"); return p[0] + "".join(x.capitalize() for x in p[1:])

def schema():
    out = ["-- CityShield schema (MySQL 8 / H2 MySQL-mode). GENERATED by data/tools/generate_backend_code.py from spec.py.",
           "-- Only CREATE TABLE IF NOT EXISTS: existing data is never dropped or altered.", ""]
    for name, cls, cols, extra in TABLES:
        lines, fks, checks = [], [], []
        for c, t, f in cols:
            d = f"  {c} {sqltype(t)}"
            if "pk" in f.split(): d += " NOT NULL AUTO_INCREMENT PRIMARY KEY"
            else:
                if "nn" in f.split(): d += " NOT NULL"
                for tok in re.findall(r"default=('[^']*'|\S+)", f): d += f" DEFAULT {tok}"
                if "uq" in f.split(): d += " UNIQUE"
            lines.append(d)
            m = re.search(r"fk=(\w+)\.(\w+)", f)
            if m: fks.append(f"  CONSTRAINT fk_{name}_{c} FOREIGN KEY ({c}) REFERENCES {m.group(1)}({m.group(2)})")
            m = re.search(r"check=(.*?)(?= default=| fk=|$)", f)
            if m: checks.append(f"  CONSTRAINT ck_{name}_{c} CHECK ({m.group(1)})")
        body = lines + fks + checks + [f"  {e}" for e in extra]
        out.append(f"CREATE TABLE IF NOT EXISTS {name} (\n" + ",\n".join(body) + "\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n")
    return "\n".join(out)

def entity(name, cls, cols):
    imp = ["jakarta.persistence.*"]
    if any(t == "T" for _, t, _ in cols): imp.append("java.time.LocalDateTime")
    s = "package com.cityshield.entity;\n\n" + "".join(f"import {i};\n" for i in imp)
    s += f"\n/** Maps table {name}. GENERATED by data/tools/generate_backend_code.py. Foreign keys are plain id fields. */\n"
    s += f"@Entity\n@Table(name = \"{name}\")\npublic class {cls} {{\n"
    for c, t, f in cols:
        if "pk" in f.split(): s += "    @Id\n    @GeneratedValue(strategy = GenerationType.IDENTITY)\n"
        s += f"    @Column(name = \"{c}\")\n    public {javatype(t)} {camel(c)};\n\n"
    s += f"    public {cls}() {{\n    }}\n}}\n"
    return s

REPO_EXTRA = {
 "EmergencyIncident": ["List<EmergencyIncident> findByStatusIn(Collection<String> statuses);", "long countByStatusIn(Collection<String> statuses);", "long countByStatus(String status);", "boolean existsByIncidentCode(String code);"],
 "ResponseTeam": ["List<ResponseTeam> findByAvailability(String availability);"],
 "IncidentResourceRequirement": ["List<IncidentResourceRequirement> findByIncidentIdIn(Collection<Long> ids);", "List<IncidentResourceRequirement> findByIncidentId(Long id);", "void deleteByIncidentId(Long id);"],
 "IncidentStatusHistory": ["List<IncidentStatusHistory> findByIncidentIdOrderByChangedAtAsc(Long id);"],
 "IncidentLog": ["List<IncidentLog> findByIncidentIdOrderByLoggedAtAsc(Long id);", "List<IncidentLog> findByIncidentIdIn(Collection<Long> ids);"],
 "IncidentAssignment": ["List<IncidentAssignment> findByStatus(String status);", "List<IncidentAssignment> findByIncidentId(Long id);", "List<IncidentAssignment> findByIncidentIdAndStatus(Long id, String status);"],
 "ResourceInventory": ["List<ResourceInventory> findByResourceTypeId(Long id);", "ResourceInventory findByZoneIdAndResourceTypeId(Long zoneId, Long typeId);"],
 "ResourceAllocation": ["List<ResourceAllocation> findAllByOrderByCreatedAtDescAllocationIdDesc();"],
 "EmergencyTypeTeamCompat": ["List<EmergencyTypeTeamCompat> findByTypeId(Long id);"],
 "AlgorithmExecutionLog": ["List<AlgorithmExecutionLog> findByAlgorithmOrderByRunAtDesc(String a);", "List<AlgorithmExecutionLog> findAllByOrderByRunAtDesc();"],
 "BenchmarkResult": ["List<BenchmarkResult> findByAlgorithmOrderByInputSizeAsc(String a);", "void deleteByAlgorithm(String a);"],
 "RoadConnection": ["List<RoadConnection> findByStatus(String status);"],
 "DeliveryRouteStop": ["List<DeliveryRouteStop> findByRouteIdOrderByStopOrderAsc(Long id);"],
}
def repo(cls):
    extra = REPO_EXTRA.get(cls, [])
    s = "package com.cityshield.repository;\n\nimport com.cityshield.entity.*;\nimport java.util.Collection;\nimport java.util.List;\nimport org.springframework.data.jpa.repository.JpaRepository;\n\n"
    s += f"public interface {cls}Repository extends JpaRepository<{cls}, Long> {{\n" + "".join(f"    {m}\n" for m in extra) + "}\n"
    return s

os.makedirs(os.path.join(B, "resources", "db"), exist_ok=True)
open(os.path.join(B, "resources", "db", "schema.sql"), "w").write(schema())
for d in ("entity", "repository"): os.makedirs(os.path.join(B, "java", "com", "cityshield", d), exist_ok=True)
for name, cls, cols, _ in TABLES:
    open(os.path.join(B, "java/com/cityshield/entity", cls + ".java"), "w").write(entity(name, cls, cols))
    open(os.path.join(B, "java/com/cityshield/repository", cls + "Repository.java"), "w").write(repo(cls))
print("generated", len(TABLES), "tables")
